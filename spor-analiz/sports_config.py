SPORT_OPTIONS = list(SPORTS_CONFIG.keys())


def get_sport_config(name):
    return SPORTS_CONFIG.get(name) or SPORTS_CONFIG["Futbol"]


def get_participant_labels(name):
    return get_sport_config(name)["participants"]


def score_unit(name):
    return get_sport_config(name)["unit"]


def get_bet_options_for_sport(name, football_options):
    cfg = get_sport_config(name)
    family = cfg["family"]

    if name == "Futbol":
        return list(football_options)

    if family == "combat":
        return [
            "Maç Kazananı",
            "Diğer / El ile Gir...",
        ]

    if family == "sets":
        return [
            "Maç Kazananı",
            "Toplam Set Üst/Alt",
            "Set Handikapı",
            "Doğru Skor",
            "Diğer / El ile Gir...",
        ]

    if family == "esports":
        return [
            "Maç Kazananı",
            "Toplam Harita Üst/Alt",
            "Harita Handikapı",
            "Takım Toplam Harita Üst/Alt",
            "Doğru Skor",
            "Diğer / El ile Gir...",
        ]

    if family == "runs":
        return [
            "Maç Kazananı",
            "Toplam Run Üst/Alt",
            "Handikap",
            "Takım Toplam Run Üst/Alt",
            "Diğer / El ile Gir...",
        ]

    if family == "points":
        options = [
            "Maç Kazananı",
            "Toplam Sayı Üst/Alt",
            "Handikap",
            "Takım Toplam Sayı Üst/Alt",
        ]
        if name == "Basketbol":
            options.extend([
                "Oyuncu Sayı Üst/Alt",
                "Oyuncu Ribaund Üst/Alt",
                "Oyuncu Asist Üst/Alt",
                "Oyuncu Üçlük Üst/Alt",
                "Oyuncu Top Çalma Üst/Alt",
                "Oyuncu Blok Üst/Alt",
                "Oyuncu Sayı + Ribaund + Asist Üst/Alt",
            ])
        options.append("Diğer / El ile Gir...")
        return options

    return [
        "Maç Kazananı",
        "Toplam Gol Üst/Alt",
        "Handikap",
        "Takım Toplam Gol Üst/Alt",
        "Doğru Skor",
        "Diğer / El ile Gir...",
    ]
