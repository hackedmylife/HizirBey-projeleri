def hesapla():
    global sonuc_metni
    try:
        text = yapistirma_alani.get("1.0", tk.END)
        lines = [line for line in text.splitlines() if "Deposit" in line or "Withdraw" in line]

        deposits, withdraws = [], []
        for line in lines:
            amounts = re.findall(r"([\d.,]+)\s*TRY", line)
            if not amounts:
                continue
            value = float(amounts[0].replace(",", ""))
            if "Deposit" in line:
                deposits.append(value)
            else:
                withdraws.append(value)

        tl = lambda x: f"{x:,.0f}".replace(",", ".")
        total_dep = sum(deposits)
        total_wd = sum(withdraws)
        net = total_dep - total_wd

        sonuc_metni = f"Toplam yatırımınız {tl(total_dep)} TL, çekiminiz {tl(total_wd)} TL ve net farkınız {tl(net)} TL'dir."
        sonuc_etiketi.config(text=sonuc_metni)
        detay_etiketi.config(text=f"({len(deposits)} yatırım, {len(withdraws)} çekim bulundu)")
        kopyala()
    except Exception as e:
        messagebox.showerror("Hata", f"Bir sorun oluştu:\n{e}")

